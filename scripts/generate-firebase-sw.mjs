import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

function loadEnv() {
    const env = {};
    const path = resolve(root, '.env');

    try {
        const content = readFileSync(path, 'utf8');
        for (const line of content.split('\n')) {
            const trimmed = line.trim();
            if (!trimmed || trimmed.startsWith('#')) continue;
            const index = trimmed.indexOf('=');
            if (index === -1) continue;
            const key = trimmed.slice(0, index).trim();
            let value = trimmed.slice(index + 1).trim();
            if (
                (value.startsWith('"') && value.endsWith('"')) ||
                (value.startsWith("'") && value.endsWith("'"))
            ) {
                value = value.slice(1, -1);
            }
            env[key] = value;
        }
    } catch {
        // .env is optional in CI if vars are injected another way
    }

    return env;
}

const env = { ...loadEnv(), ...process.env };

const required = [
    'VITE_FIREBASE_API_KEY',
    'VITE_FIREBASE_AUTH_DOMAIN',
    'VITE_FIREBASE_PROJECT_ID',
    'VITE_FIREBASE_STORAGE_BUCKET',
    'VITE_FIREBASE_MESSAGING_SENDER_ID',
    'VITE_FIREBASE_APP_ID',
];

const missing = required.filter((key) => !env[key]);
if (missing.length) {
    console.error(`Missing Firebase env vars: ${missing.join(', ')}`);
    process.exit(1);
}

const output = `// Generated by scripts/generate-firebase-sw.mjs — do not edit manually
importScripts('https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js');

firebase.initializeApp({
    apiKey: '${env.VITE_FIREBASE_API_KEY}',
    authDomain: '${env.VITE_FIREBASE_AUTH_DOMAIN}',
    projectId: '${env.VITE_FIREBASE_PROJECT_ID}',
    storageBucket: '${env.VITE_FIREBASE_STORAGE_BUCKET}',
    messagingSenderId: '${env.VITE_FIREBASE_MESSAGING_SENDER_ID}',
    appId: '${env.VITE_FIREBASE_APP_ID}',
});

const messaging = firebase.messaging();

messaging.onBackgroundMessage(function (payload) {
    const notificationTitle = payload.notification?.title || 'Buddie-X';
    const notificationOptions = {
        body: payload.notification?.body || '',
        icon: '/logo/BX_4.png',
        data: payload.data || {},
    };

    self.registration.showNotification(notificationTitle, notificationOptions);
});
`;

writeFileSync(resolve(root, 'public/firebase-messaging-sw.js'), output);
console.log('Generated public/firebase-messaging-sw.js');
